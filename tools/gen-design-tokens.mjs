#!/usr/bin/env node
/**
 * gen-design-tokens.mjs — 由 data/design-tokens.json 生成 C# 静态类 DesignTokens
 *
 * V9 §19.1 C2 要求「设计 Token 直接落为 C# 静态类，设计与代码一一对应」。
 * 生成 + --check 才能保证"改 token 就改一处"。
 *
 * 独立验证轨（S4/S5）指出后修正的三处：
 *   1. 标识符清洗：token 键含空格/非法字符时，pascal() 会产出不能编译的 C# → 严格清洗并校验；
 *   2. 字面量安全：字符串值必须转义引号/反斜杠，数值必须有限（拒绝 Infinity/NaN）；
 *   3. 数值 token **全覆盖**：旧版按"键名后缀"启发式筛选，静默丢掉 15 个有意义的数值 token
 *      （font.*.sizePx / spacing.* / radius.* / layers.*.readSeconds / touch.lookSensitivityDefault）——
 *      现改为**递归收集所有数值叶子**，一个不漏。
 *
 * 用法：node tools/gen-design-tokens.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'data/design-tokens.json');
const OUT = path.join(ROOT, 'unity/Assets/Scripts/Core/DesignTokens.cs');

const tokens = JSON.parse(fs.readFileSync(SRC, 'utf8'));

/** 严格标识符清洗：非 [A-Za-z0-9_] 一律当作分隔，转 PascalCase；首字符必须是字母/下划线 */
function pascal(raw, trail = '') {
  // 保留字母与数字；其它字符作分隔。**数字必须保留**：旧规则把它删掉后
  // layers.L0_fatal 与 layers.L1_tactical 会撞成同一个 LayersL（实测碰撞）。
  const cleaned = String(raw).replace(/[^A-Za-z0-9]+/g, ' ').trim();
  const parts = cleaned.length ? cleaned.split(/\s+/) : [];
  let name = parts.map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
  if (!name) name = 'Unnamed';
  if (!/^[A-Za-z_]/.test(name)) name = 'N' + name;
  return name + trail;
}
const csString = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r?\n/g, '\\n') + '"';
const csFloat = (n) => {
  if (!Number.isFinite(n)) throw new Error(`token 数值不是有限数：${n}（C# 字面量无法表达）`);
  return Number.isInteger(n) ? `${n}f` : `${n}f`;
};

/** 递归收集数值叶子：路径 → 数值（全覆盖，不做后缀启发式） */
function numericLeaves(obj, prefix = '', out = []) {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith('_')) continue;
    const name = prefix ? `${prefix}_${k}` : k;
    if (typeof v === 'number') out.push([name, v]);
    else if (v && typeof v === 'object' && !Array.isArray(v)) numericLeaves(v, name, out);
  }
  return out;
}

const colors = tokens.color ?? {};
const numbers = numericLeaves(
  Object.fromEntries(Object.entries(tokens).filter(([g]) => g !== 'color' && g !== 'meta')),
);

// 唯一性检查：清洗后重名会生成重复常量 → 编译错误，必须提前 fail
const seen = new Map();
const generatedNames = [
  ...Object.keys(colors).map((k) => ({ name: 'Color' + pascal(k), from: `color.${k}` })),
  ...numbers.map(([n]) => ({ name: pascal(n), from: `token.${n}` })),
];
for (const { name, from } of generatedNames) {
  if (seen.has(name)) throw new Error(`生成后常量名冲突：${name}（来自 ${seen.get(name)} 与 ${from}）—— 请调整清洗规则或 token 名`);
  seen.set(name, from);
}

const lines = [];
lines.push('// <auto-generated>');
lines.push('/// <summary>');
lines.push('/// 设计 Token（V9 §19.1 C2）：颜色与数值常量的唯一定义处，由 data/design-tokens.json 生成。');
lines.push('/// </summary>');
lines.push('//   由 tools/gen-design-tokens.mjs 从 data/design-tokens.json 生成，请勿手改。');
lines.push('//   V9 §19.1 C2：设计 Token 直接落为 C# 静态类，设计与代码一一对应。');
lines.push('//   重新生成：node tools/gen-design-tokens.mjs    CI 校验：--check');
lines.push(`//   来源 token 顶层分组：${Object.keys(tokens).join(' / ')}`);
lines.push(`//   生成覆盖：颜色 ${Object.keys(colors).length} 个 · 数值 ${numbers.length} 个（递归全量，非后缀筛选取样）`);
lines.push('// </auto-generated>');
lines.push('');
lines.push('namespace Whisper.Core');
lines.push('{');
lines.push('    public static class DesignTokens');
lines.push('    {');
lines.push('        // ── 颜色 ──');
for (const [k, v] of Object.entries(colors)) {
  lines.push(`        /// <summary>${k} = ${v}</summary>`);
  lines.push(`        public const string Color${pascal(k)} = ${csString(v)};`);
}
lines.push('');
lines.push('        // ── 数值（尺寸 / 时长 / 半径 / 间距 / 层级读数等，递归全量）──');
for (const [name, value] of numbers) {
  lines.push(`        /// <summary>token 路径 ${name} = ${value}</summary>`);
  lines.push(`        public const float ${pascal(name)} = ${csFloat(value)};`);
}
lines.push('');
lines.push('        /// <summary>运行时真源（Unity 工程内路径，运行时可直接读）。</summary>');
lines.push('        public const string SourcePath = "Assets/Data/design-tokens.json";');
lines.push('    }');
lines.push('}');
lines.push('');

const want = lines.join('\n');
const checkOnly = process.argv.includes('--check');

// Unity 内镜像一致性：Assets/Data/design-tokens.json 是**运行时真源**，
// 仓库根 data/design-tokens.json 是**管线真源**（工具的输入）。两者必须逐字节一致，
// 否则会出现"改了 token、游戏里没变"这类静默漂移。
const MIRROR = path.join(ROOT, 'unity/Assets/Data/design-tokens.json');
function mirrorProblems() {
  const src = fs.readFileSync(SRC);
  if (!fs.existsSync(MIRROR)) return [`Unity 内镜像缺失：${path.relative(ROOT, MIRROR)}（同步：cp data/design-tokens.json unity/Assets/Data/）`];
  return src.equals(fs.readFileSync(MIRROR)) ? [] : [`Unity 内镜像与管线真源不一致：${path.relative(ROOT, MIRROR)}`];
}
const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;

// 产物合法性自检（独立验证轨 S4：旧版 --check 只比对漂移，从不校验产物合法性）
function selfValidate(text) {
  const problems = [];
  if (!text.startsWith('// <auto-generated>')) problems.push('缺 <auto-generated> 标记');
  const opens = (text.match(/\{/g) ?? []).length;
  const closes = (text.match(/\}/g) ?? []).length;
  if (opens !== closes) problems.push(`花括号不配平（${opens} vs ${closes}）`);
  for (const m of text.matchAll(/public const string (\w+) = (".*?");/g)) {
    if (!/^[A-Za-z_]\w*$/.test(m[1])) problems.push(`非法标识符：${m[1]}`);
  }
  for (const m of text.matchAll(/public const float (\w+) = ([^;]+);/g)) {
    if (!/^[A-Za-z_]\w*$/.test(m[1])) problems.push(`非法标识符：${m[1]}`);
    if (!/^-?\d+(\.\d+)?f$/.test(m[2].trim())) problems.push(`非法浮点字面量：${m[1]} = ${m[2]}`);
  }
  return problems;
}

const wantProblems = selfValidate(want);
if (wantProblems.length) {
  console.log('[tokens] 生成物自身不合法，拒绝写出 ✗');
  for (const p of wantProblems) console.log('  ✗ ' + p);
  process.exit(1);
}

if (checkOnly) {
  const haveProblems = have ? selfValidate(have) : ['文件不存在'];
  const mirrors = mirrorProblems();
  if (have === want && haveProblems.length === 0 && mirrors.length === 0) {
    console.log('[tokens] DesignTokens.cs 与真源一致 + 产物自检通过 + Unity 内镜像一致 ✓');
    process.exit(0);
  }
  console.log('[tokens] 漂移 / 产物不合法 / 镜像不一致 ✗');
  for (const p of [...haveProblems, ...mirrors]) console.log('  ✗ ' + p);
  process.exit(1);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, want, 'utf8');
// 同步运行时镜像（管线真源 → Unity Assets）
fs.mkdirSync(path.dirname(MIRROR), { recursive: true });
fs.copyFileSync(SRC, MIRROR);
console.log(`[tokens] 生成 DesignTokens.cs：颜色 ${Object.keys(colors).length} 个 + 数值 ${numbers.length} 个（递归全量），产物自检通过`);
